// Copies the card CSV files in data/cards into a TypeScript module, so the pure packages can read them without file I/O
// (engineering design §7.2). Run after editing a CSV: `npm run data`. A test fails if the module is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const FILES = ['command-cards', 'weather-cards', 'crew-cards', 'treasure-map-cards'];

export function generate() {
  const lines = [
    '// Generated by packages/msb-data/scripts/generate.mjs from data/cards/*.csv. Do not edit: edit the CSV and run `npm run data`.',
    '',
  ];
  for (const name of FILES) {
    const text = readFileSync(join(root, 'data', 'cards', `${name}.csv`), 'utf8').replace(/^﻿/, '');
    const constName = name.toUpperCase().replace(/-/g, '_') + '_CSV';
    lines.push(`export const ${constName} = ${JSON.stringify(text)};`, '');
  }
  return lines.join('\n');
}

export const OUTPUT = join(root, 'packages', 'msb-data', 'src', 'generated', 'csv.ts');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generate());
  console.log(`Wrote ${OUTPUT}`);
}
